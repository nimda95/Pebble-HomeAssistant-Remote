#!/usr/bin/env node
// Builds the settings page into one HTML file, gzips it and embeds it in the PebbleKit JS bundle
// as base64 (src/pkjs/generated/config_page.js). At runtime the phone inflates it and opens it
// as a data: URL. Also generates src/pkjs/generated/default_config.js from examples/default.yaml.
//
//   node tools/build-config-page.js            # normal build
//   node tools/build-config-page.js --preview  # also writes config/preview.html for a browser
'use strict';
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const esbuild = require('esbuild');
const yaml = require('js-yaml');

const root = path.join(__dirname, '..');
const gen = path.join(root, 'src/pkjs/generated');
fs.mkdirSync(gen, { recursive: true });

function replaceOnce(haystack, marker, value) {
  if (haystack.indexOf(marker) < 0) throw new Error('marker not found: ' + marker);
  return haystack.replace(marker, () => value);
}

async function main() {
  const js = await esbuild.build({
    entryPoints: [path.join(root, 'config/app.js')],
    bundle: true,
    minify: true,
    format: 'iife',
    target: ['es2017', 'safari13'],
    platform: 'browser',
    write: false,
    legalComments: 'none',
  });
  let script = js.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

  const css = await esbuild.transform(fs.readFileSync(path.join(root, 'config/style.css'), 'utf8'), {
    loader: 'css',
    minify: true,
  });

  let html = fs.readFileSync(path.join(root, 'config/index.html'), 'utf8');
  html = replaceOnce(html, '/*__STYLE__*/', css.code.trim());
  html = replaceOnce(html, '/*__SCRIPT__*/', script);
  // collapse indentation outside <pre> blocks
  html = html.split(/(<pre[\s\S]*?<\/pre>)/).map((part, i) => (i % 2 ? part : part.replace(/\n\s+/g, '\n'))).join('');

  const gz = zlib.gzipSync(Buffer.from(html, 'utf8'), { level: 9 });
  const b64 = gz.toString('base64');
  fs.writeFileSync(
    path.join(gen, 'config_page.js'),
    '// GENERATED by tools/build-config-page.js from config/. Do not edit.\n' +
      '// base64(gzip(settings page HTML)), inflated and opened as a data: URL by index.js.\n' +
      'module.exports = ' + JSON.stringify(b64) + ';\n'
  );

  const defYaml = fs.readFileSync(path.join(root, 'examples/default.yaml'), 'utf8');
  const defConfig = yaml.load(defYaml);
  fs.writeFileSync(
    path.join(gen, 'default_config.js'),
    '// GENERATED by tools/build-config-page.js from examples/default.yaml. Do not edit.\n' +
      'module.exports = ' + JSON.stringify({ yaml: defYaml, config: defConfig }) + ';\n'
  );

  console.log(
    'config page: html %d KB -> gzip %d KB -> base64 %d KB (script %d KB)',
    Math.round(html.length / 1024), Math.round(gz.length / 1024), Math.round(b64.length / 1024), Math.round(script.length / 1024)
  );

  if (process.argv.includes('--preview')) {
    const assets = require(path.join(gen, 'assets.js'));
    const init = {
      version: 'preview',
      settings: { url: '', token: '' },
      yaml: defYaml,
      defaultYaml: defYaml,
      platform: null,
      screen: null,
      entities: [
        { id: 'media_player.living_room_tv', name: 'Living Room TV' },
        { id: 'remote.living_room_tv', name: 'Living Room TV' },
      ],
      iconCache: {},
      assets,
    };
    const page = replaceOnce(html, '"__PEBBLE_INIT__"', JSON.stringify(init).replace(/</g, '\\u003c'));
    fs.writeFileSync(path.join(root, 'config/preview.html'), page);
    console.log('wrote config/preview.html');
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
