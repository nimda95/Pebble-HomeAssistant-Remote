#!/usr/bin/env node
// Builds src/pkjs/generated/assets.js: base64(gzip(JSON)) holding
//  - the universal-remote-card platform maps and brand icons (data/urc.json)
//  - the SVG paths of every Material Design Icon those maps reference, plus a curated extra set.
// Icons outside this set are loaded at runtime from Home Assistant's own /static/mdi/ files and cached.
'use strict';
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const mdi = require('@mdi/js');

const root = path.join(__dirname, '..');
const urc = JSON.parse(fs.readFileSync(path.join(root, 'data/urc.json'), 'utf8'));

// Extra icons that are handy for custom buttons on a TV remote.
const EXTRA = `
remote remote-tv television television-classic monitor projector speaker speaker-wireless soundbar
lightbulb lightbulb-outline lightbulb-group ceiling-light lamp fan air-conditioner thermostat
blinds curtains window-shutter power-plug power-socket gamepad-variant controller-classic
playlist-play playlist-music shuffle shuffle-variant repeat repeat-once repeat-off music music-note
movie movie-open filmstrip youtube-subscription cast cast-connected cast-off apps view-grid
format-list-bulleted dots-horizontal dots-vertical arrow-left arrow-right arrow-up-bold arrow-down-bold
chevron-double-left chevron-double-right chevron-double-up chevron-double-down plus minus close check
home-variant home-outline account account-group star heart thumb-up thumb-down bell bell-off
microphone microphone-off volume-off volume-plus volume-minus volume-source brightness-6 brightness-5
brightness-7 weather-night theme-light-dark timer timer-outline alarm sleep power-standby restart
information-outline help-circle-outline cog-outline tune tune-variant filter magnify-close
format-text subtitles-outline translate translate-variant aspect-ratio fullscreen fullscreen-exit
picture-in-picture-bottom-right numeric record-rec skip-backward-outline skip-forward-outline
rewind-10 rewind-30 fast-forward-10 fast-forward-30 play-circle pause-circle stop-circle
play-pause skip-next-circle skip-previous-circle eject spotify netflix youtube plex kodi twitch
amazon apple google google-play android hulu vlc steam emby jellyfish television-guide
television-play television-off radio podcast hdmi-port video-input-hdmi bluetooth wifi lan
lightning-bolt flash script-text play-box-outline playlist-star robot-vacuum door garage lock
lock-open-variant cctv doorbell-video
snowflake fire thermometer thermometer-plus thermometer-minus water-percent sun-snowflake-variant
heat-wave weather-windy fan-auto fan-speed-1 fan-speed-2 fan-speed-3 fan-off hvac hvac-off
air-filter air-purifier air-humidifier radiator lightbulb-on lightbulb-off ceiling-fan
`.split(/\s+/).filter(Boolean);

function camel(name) {
  return 'mdi' + name.split('-').map((s) => s[0].toUpperCase() + s.slice(1)).join('');
}

const wanted = new Set(EXTRA);
(function walk(o) {
  if (Array.isArray(o)) return o.forEach(walk);
  if (o && typeof o === 'object') {
    for (const k of Object.keys(o)) {
      if (k === 'icon' && typeof o[k] === 'string' && /^(mdi|hass):/.test(o[k])) wanted.add(o[k].replace(/^(mdi|hass):/, ''));
      else walk(o[k]);
    }
  }
})(urc.platforms);

const icons = {};
const missing = [];
for (const name of Array.from(wanted).sort()) {
  const p = mdi[camel(name)];
  if (p) icons[name] = p;
  else missing.push(name);
}
if (missing.length) console.log('note: %d icon(s) referenced by universal-remote-card are not in MDI %s and show as text: %s', missing.length, require('@mdi/js/package.json').version, missing.join(' '));

const payload = {
  mdiVersion: require('@mdi/js/package.json').version,
  urcVersion: urc.version,
  mdi: icons,
  brand: urc.icons,
  platforms: urc.platforms,
};
const json = JSON.stringify(payload);
const gz = zlib.gzipSync(Buffer.from(json, 'utf8'), { level: 9 });
const b64 = gz.toString('base64');

const outDir = path.join(root, 'src/pkjs/generated');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  path.join(outDir, 'assets.js'),
  '// GENERATED by tools/build-assets.js. Do not edit.\n' +
    '// base64(gzip(JSON)): platform key maps from universal-remote-card (Apache-2.0) and\n' +
    '// Material Design Icons paths (Apache-2.0, Pictogrammers).\n' +
    'module.exports = ' + JSON.stringify(b64) + ';\n'
);
console.log(
  'assets: %d mdi icons, %d brand icons, %d platforms; json %d KB -> gzip %d KB -> base64 %d KB',
  Object.keys(icons).length, Object.keys(urc.icons).length, Object.keys(urc.platforms).length,
  Math.round(json.length / 1024), Math.round(gz.length / 1024), Math.round(b64.length / 1024)
);
