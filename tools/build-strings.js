#!/usr/bin/env node
// Packs the translations in src/pkjs/lang/ (all languages but English, which is built into
// src/pkjs/lib/i18n.js) into src/pkjs/generated/strings.js as base64(gzip(JSON)). The phone
// inflates it when it needs another language and hands it to the settings page.
'use strict';
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const { LANGS } = require('../src/pkjs/lib/i18n');

const root = path.join(__dirname, '..');
const out = {};
for (const code of LANGS) {
  if (code === 'en') continue;
  const file = path.join(root, 'src/pkjs/lang', code + '.js');
  delete require.cache[require.resolve(file)];
  out[code] = require(file);
}
const json = JSON.stringify(out);
const b64 = zlib.gzipSync(Buffer.from(json, 'utf8'), { level: 9 }).toString('base64');
fs.mkdirSync(path.join(root, 'src/pkjs/generated'), { recursive: true });
fs.writeFileSync(
  path.join(root, 'src/pkjs/generated/strings.js'),
  '// GENERATED by tools/build-strings.js from src/pkjs/lang/. Do not edit.\n' +
    '// base64(gzip(JSON)) of every language except English, loaded by src/pkjs/lib/i18n.js.\n' +
    'module.exports = ' + JSON.stringify(b64) + ';\n'
);
console.log('strings: %d languages, json %d KB -> base64 %d KB', Object.keys(out).length,
  Math.round(json.length / 1024), Math.round(b64.length / 1024));
